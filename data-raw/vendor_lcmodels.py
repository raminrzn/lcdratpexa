# Copy, verbatim, the parts of NCI's lcmodels 4.1.3 (GPL-2) that compute
# LCDRAT: risk.kovalchik() and cuts() from R/lcmodels.R and checkImputed()
# from R/source.R. Writes R/lcmodels_code.R.
# usage: python3 vendor_lcmodels.py <unpacked lcmodels source dir> <out.R>
import sys, os
src = os.path.join(sys.argv[1], "R")
lc = open(os.path.join(src, "lcmodels.R")).read().split("\n")
so = open(os.path.join(src, "source.R")).read().split("\n")

def block(lines, start, stop):
    i = next(k for k, l in enumerate(lines) if l.startswith(start))
    j = next(k for k in range(i + 1, len(lines)) if lines[k].startswith(stop))
    while lines[j - 1].strip() == "" or lines[j - 1].startswith("#"):
        j -= 1
    return "\n".join(lines[i:j]).rstrip() + "\n"

parts = [
    block(lc, "risk.kovalchik <- function", "risk.pittsburgh <- function"),
    block(lc, "cuts <- function", "#'"),
    block(so, "checkImputed <- function", "checkCounterfactual <- function"),
]
hdr = ("# Copied verbatim from NCI's lcmodels R package, version 4.1.3 (2026-03-31),\n"
       "# https://dceg.cancer.gov/tools/risk-assessment/lcmodels (GPL-2; authors Li C.\n"
       "# Cheung, Stephanie A. Kovalchik, Hormuzd A. Katki). Created by US Federal\n"
       "# Government employees; not intended for treating or diagnosing human subjects.\n"
       "# Generated by data-raw/vendor_lcmodels.py; do not edit.\n\n")
open(sys.argv[2], "w").write(hdr + "\n".join(parts))
print("wrote", sys.argv[2], sum(p.count("\n") for p in parts), "lines")
